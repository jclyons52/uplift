// emitFunction emits a top-level function declaration.
func (tr *transpiler) emitFunction(n tsmorph.Node) error {
	name := n.Name()
	params, ret, err := tr.signatureFromChildren(n)
	if err != nil {
		return err
	}
	tr.out.line("func " + name + "(" + params + ")" + ret + " {")
	tr.out.indent()
	if body, ok := n.GetBody(); ok {
		if err := tr.emitBlock(body); err != nil {
			return err
		}
	} else {
		tr.out.line("panic(\"not implemented\")")
	}
	tr.out.dedent()
	tr.out.line("}")
	tr.out.blank()
	return nil
}

// emitVariableStatement emits `const x = ...` / `let x: T = ...`.
func (tr *transpiler) emitVariableStatement(n tsmorph.Node) error {
	vs, _ := n.AsVariableStatement()
	for _, d := range vs.Declarations() {
		name := d.Name()
		init, hasInit := d.Initializer()
		tn, hasType := d.TypeNode()
		var typ string
		if hasType {
			t, err := tr.goType(tn)
			if err != nil {
				return err
			}
			typ = t
		}
		if hasInit {
			// Object literals with a declared type → typed struct literal
			// (the checker types the literal as an anonymous __object).
			if ast.IsObjectLiteralExpression(init.ASTNode()) && typ != "" && typ != "any" {
				expr, err := tr.typedObjectLiteral(init, typ)
				if err != nil {
					return err
				}
				tr.out.line("var " + name + " " + typ + " = " + expr)
				continue
			}
			expr, err := tr.emitExpr(init)
			if err != nil {
				return err
			}
			if typ != "" && typ != "any" {
				tr.out.line("var " + name + " " + typ + " = " + expr)
			} else {
				tr.out.line(name + " := " + expr)
			}
		} else if typ != "" {
			tr.out.line("var " + name + " " + typ)
		}
	}
	return nil
}

