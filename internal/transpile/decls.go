// emitPreamble writes the package clause, the post-work manifest (so the
// LLM's TODO list travels with the code), and the stdlib imports that the
// emitted code actually references.
func (tr *transpiler) emitPreamble() error {
	tr.out.line("// Code generated by ts2go from TypeScript. DO NOT EDIT.")
	tr.out.blank()
	if m := tr.buildReport(true).Manifest(); m != "" {
		for _, l := range strings.Split(strings.TrimSuffix(m, "\n"), "\n") {
			tr.out.line(l)
		}
		tr.out.blank()
	}
	tr.out.line("package " + tr.pkgName)
	tr.out.blank()
	var imports []string
	for _, pkg := range []string{"fmt", "strings", "math", "maps", "strconv", "errors", "regexp"} {
		if tr.used[pkg] {
			imports = append(imports, `"`+pkg+`"`)
		}
	}
	if tr.usedShim && tr.emitShim {
		// The shim source is appended to this file and needs these; when
		// the shim lives in its own file (multi-file packages) it declares
		// its own imports.
		for _, pkg := range []string{"fmt", "sync", "time", "reflect", "regexp", "strings"} {
			if !slices.Contains(imports, `"`+pkg+`"`) {
				imports = append(imports, `"`+pkg+`"`)
			}
		}
	}
	slices.Sort(imports)
	if len(imports) > 0 {
		tr.out.line("import (")
		tr.out.indent()
		for _, i := range imports {
			tr.out.line(i)
		}
		tr.out.dedent()
		tr.out.line(")")
		tr.out.blank()
	}
	return nil
}

// transpileStatement dispatches a top-level (or nested) statement.
func (tr *transpiler) transpileStatement(n tsmorph.Node, topLevel bool) error {
	switch {
	case ast.IsInterfaceDeclaration(n.ASTNode()):
		return tr.emitInterface(n)
	case ast.IsClassDeclaration(n.ASTNode()):
		return tr.emitClass(n)
	case ast.IsEnumDeclaration(n.ASTNode()):
		return tr.emitEnum(n)
	case ast.IsTypeAliasDeclaration(n.ASTNode()):
		return tr.emitTypeAlias(n)
	case ast.IsFunctionDeclaration(n.ASTNode()):
		return tr.emitFunction(n)
	case ast.IsVariableStatement(n.ASTNode()):
		// `const x = require("...")` — treat require like an import.
		if tr.handleCommonJSRequireStatement(n) {
			return nil
		}
		return tr.emitVariableStatement(n)
	case ast.IsImportDeclaration(n.ASTNode()):
		return tr.handleImport(n)
	case ast.IsExportDeclaration(n.ASTNode()):
		return tr.handleExport(n)
	default:
		return tr.emitStatement(n)
	}
}

// importBindingNames extracts the local identifiers bound by an import
// declaration: `import fs from "x"`, `import {a, b as c} from "x"`,
// `import * as ns from "x"`. Side-effect imports (`import "x"`) bind none.
func importBindingNames(txt string) []string {
	body := strings.TrimSpace(txt)
	body = strings.TrimSpace(strings.TrimPrefix(body, "import"))
	if i := strings.Index(body, "from"); i >= 0 {
		body = body[:i]
	}
	body = strings.TrimSpace(strings.Trim(body, "\"'`"))
	if body == "" || body == "{" {
		return nil
	}
	if strings.HasPrefix(body, "*") {
		// `* as ns`
		body = strings.Replace(body, "* as ", "", 1)
	}
	body = strings.Trim(body, "{}")
	var out []string
	for _, part := range strings.Split(body, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		if j := strings.Index(part, " as "); j >= 0 {
			part = strings.TrimSpace(part[j+4:])
		}
		part = strings.TrimSpace(strings.Trim(part, "\"'`"))
		if part != "" {
			out = append(out, part)
		}
	}
	return out
}

// handleImport maps a TS import to nothing (Go packages have no import
// statements for same-package files): imports that resolve to another file
// of the same Go package are dropped — the identifiers resolve directly —
// while imports of sibling packages and external modules become work items
// the LLM must wire up.
func (tr *transpiler) handleImport(n tsmorph.Node) error {
	spec := tr.moduleSpecifier(n)
	if spec == "" {
		return nil
	}
	// Bindings from this import are unresolved (sibling/external) regardless
	// of classification in single-file mode; record them so dynamic-any
	// routing leaves them as resilience placeholders.
	if tr.external == nil {
		tr.external = map[string]bool{}
	}
	for _, nm := range importBindingNames(n.Text()) {
		tr.external[nm] = true
	}
	if tr.classify == nil {
		return nil // single-file mode: imports were always dropped
	}
	cls, target := tr.classify(tr.sf.FilePath(), spec)
	switch cls {
	case importSamePackage:
		return nil
	case importSiblingPackage:
		tr.recordGap(SevTodo, "import", n, "cross-package import %q — wire up the Go import (package %s)", spec, target)
	default:
		tr.recordGap(SevTodo, "import", n, "external module import %q — port or stub this module", spec)
	}
	return nil
}

// handleExport maps a TS export to nothing: exported names are already
// emitted as exported Go identifiers (PascalCase). Re-exports from sibling
// packages or external modules become work items.
func (tr *transpiler) handleExport(n tsmorph.Node) error {
	spec := tr.moduleSpecifier(n)
	if spec == "" {
		return nil
	}
	if tr.classify == nil {
		return nil
	}
	cls, target := tr.classify(tr.sf.FilePath(), spec)
	switch cls {
	case importSamePackage:
		return nil
	case importSiblingPackage:
		tr.recordGap(SevTodo, "import", n, "re-export from sibling package %q — wire up the Go import (package %s)", spec, target)
	default:
		tr.recordGap(SevTodo, "import", n, "re-export from external module %q — port or stub this module", spec)
	}
	return nil
}

// moduleSpecifier returns the module specifier text of an import/export
// declaration, or "" when the declaration has none (e.g. `export { a }`).
func (tr *transpiler) moduleSpecifier(n tsmorph.Node) string {
	node := n.ASTNode()
	if node == nil {
		return ""
	}
	ms := ast.GetExternalModuleName(node)
	if ms == nil {
		return ""
	}
	return strings.Trim(ms.Text(), `"'`)
}

