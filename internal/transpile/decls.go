// emitClass emits `class X { ... }` as a Go struct + methods. The constructor
// becomes NewX(...). `extends` becomes struct embedding.
func (tr *transpiler) emitClass(n tsmorph.Node) error {
	name := n.Name()

	// extends → embedded field.
	var embedded []string
	if ext, ok := tr.extendsName(n); ok {
		embedded = append(embedded, ext)
	}

	tr.out.line("type " + name + " struct {")
	tr.out.indent()
	for _, e := range embedded {
		tr.out.line(e)
	}
	// Regular properties.
	for _, p := range n.GetMembers() {
		if !ast.IsPropertyDeclaration(p.ASTNode()) && !ast.IsPropertySignatureDeclaration(p.ASTNode()) {
			continue
		}
		fname := exportField(p.Name())
		tn, ok := p.GetType()
		if !ok {
			typ := p.Type()
			tr.out.line(fname + " " + tr.cleanCheckerType(typ.Text()))
			continue
		}
		typ, err := tr.goType(tn)
		if err != nil {
			return err
		}
		if typ == "" {
			typ = "any"
		}
		tr.out.line(fname + " " + typ)
	}
	// Constructor parameter properties (`constructor(private name: string)`)
	// declare fields too.
	for _, m := range n.GetMembers() {
		if !ast.IsConstructorDeclaration(m.ASTNode()) {
			continue
		}
		for _, c := range m.Children() {
			if !ast.IsParameterDeclaration(c.ASTNode()) {
				continue
			}
			if !c.HasModifierPrivate() && !c.HasModifierProtected() &&
				!c.HasModifier(ast.ModifierFlagsPublic) && !c.HasModifier(ast.ModifierFlagsReadonly) {
				continue
			}
			pname := exportField(c.Name())
			tn, ok := c.GetType()
			if !ok {
				tr.out.line(pname + " " + tr.cleanCheckerType(c.Type().Text()))
				continue
			}
			typ, err := tr.goType(tn)
			if err != nil {
				return err
			}
			if typ == "" {
				typ = "any"
			}
			tr.out.line(pname + " " + typ)
		}
	}
	tr.out.dedent()
	tr.out.line("}")
	tr.out.blank()

	// Constructor → NewX(params) returning *X.
	for _, m := range n.GetMembers() {
		if !ast.IsConstructorDeclaration(m.ASTNode()) {
			continue
		}
		params, _, err := tr.signatureFromChildren(m)
		if err != nil {
			return err
		}
		tr.out.line("func New" + name + "(" + params + ") *" + name + " {")
		tr.out.indent()
		tr.out.line("r := &" + name + "{}")
		// Parameter properties: `constructor(private name: string)` assigns
		// the parameter to the generated field.
		for _, c := range m.Children() {
			if !ast.IsParameterDeclaration(c.ASTNode()) {
				continue
			}
			if !c.HasModifierPrivate() && !c.HasModifierProtected() &&
				!c.HasModifier(ast.ModifierFlagsPublic) && !c.HasModifier(ast.ModifierFlagsReadonly) {
				continue
			}
			pname := c.Name()
			tr.out.line("r." + exportField(pname) + " = " + pname)
		}
		tr.out.line("return r")
		tr.out.dedent()
		tr.out.line("}")
		tr.out.blank()
	}

	// Methods.
	for _, m := range n.GetMembers() {
		if !ast.IsMethodDeclaration(m.ASTNode()) {
			continue
		}
		if err := tr.emitMethod(name, m); err != nil {
			return err
		}
	}
	return nil
}

// extendsName returns the base class name from a class heritage clause.
func (tr *transpiler) extendsName(n tsmorph.Node) (string, bool) {
	for _, c := range n.Children() {
		if ast.IsHeritageClause(c.ASTNode()) {
			for _, t := range c.GetTypeArguments() {
				_ = t
			}
			for _, cc := range c.Children() {
				if ast.IsExpressionWithTypeArguments(cc.ASTNode()) {
					return cc.Name(), true
				}
			}
		}
	}
	return "", false
}

// emitMethod emits a Go method: `func (r *X) name(params) ret { body }`.
func (tr *transpiler) emitMethod(recv string, m tsmorph.Node) error {
	mname := m.Name()
	params, ret, err := tr.signatureFromChildren(m)
	if err != nil {
		return err
	}
	tr.out.line("func (r *" + recv + ") " + mname + "(" + params + ")" + ret + " {")
	tr.out.indent()
	if body, ok := m.GetBody(); ok {
		if err := tr.emitBlock(body); err != nil {
			return err
		}
	} else {
		tr.out.line("panic(\"not implemented\")")
	}
	tr.out.dedent()
	tr.out.line("}")
	tr.out.blank()
	return nil
}

