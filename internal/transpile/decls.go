// emitEnum emits a TS enum as a Go typed constant block with iota.
func (tr *transpiler) emitEnum(n tsmorph.Node) error {
	name := n.Name()
	members := n.GetMembers()

	isString := false
	for _, m := range members {
		if init, ok := m.GetInitializer(); ok {
			if strings.HasPrefix(strings.TrimSpace(init.Text()), `"`) {
				isString = true
				break
			}
		}
	}

	tr.out.line("type " + name + " int")
	tr.out.blank()
	tr.out.line("const (")
	tr.out.indent()
	if isString {
		for _, m := range members {
			init, ok := m.GetInitializer()
			if !ok {
				continue
			}
			tr.out.line(name + m.Name() + " " + name + " = " + strings.TrimSpace(init.Text()))
		}
	} else {
		tr.out.line(name + "Unspecified " + name + " = iota")
		for _, m := range members {
			tr.out.line(name + m.Name())
		}
	}
	tr.out.dedent()
	tr.out.line(")")
	tr.out.blank()
	return nil
}

