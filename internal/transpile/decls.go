// emitTypeAlias emits `type X = T` as `type X = T` (Go alias). Aliases whose
// names are already Go builtins (uint8, int64, ...) are skipped — the
// builtin IS the target, and `type uint8 = uint8` would be recursive.
// String-literal-union aliases become a named string type + consts.
func (tr *transpiler) emitTypeAlias(n tsmorph.Node) error {
	name := n.Name()
	info, ok := tr.aliases[name]
	if !ok {
		return fmt.Errorf("alias %s not collected", name)
	}
	if info.unionValues != nil {
		tr.out.line("type " + name + " string")
		tr.out.blank()
		tr.out.line("const (")
		tr.out.indent()
		for _, v := range info.unionValues {
			tr.out.line(name + unionConstSuffix(v) + " " + name + " = " + v)
		}
		tr.out.dedent()
		tr.out.line(")")
		tr.out.blank()
		return nil
	}
	if _, isBuiltin := primitiveAliases[name]; isBuiltin {
		return nil
	}
	tr.out.line("type " + name + " = " + info.target)
	tr.out.blank()
	return nil
}

// unionConstSuffix turns a quoted literal into an exported const-name
// suffix: `"active"` → `Active`, `"in-progress"` → `InProgress`.
func unionConstSuffix(quoted string) string {
	s := strings.Trim(quoted, `"`)
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return !('a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || '0' <= r && r <= '9')
	})
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(exportField(p))
	}
	if b.Len() == 0 {
		return "Value"
	}
	return b.String()
}

