// emitInterface emits `interface X { ... }` as a Go struct (data members) or
// a Go interface (method members).
func (tr *transpiler) emitInterface(n tsmorph.Node) error {
	name := n.Name()
	members := n.GetMembers()

	hasMethods := false
	for _, m := range members {
		if ast.IsMethodSignatureDeclaration(m.ASTNode()) ||
			ast.IsCallSignatureDeclaration(m.ASTNode()) ||
			ast.IsConstructSignatureDeclaration(m.ASTNode()) {
			hasMethods = true
			break
		}
	}
	if !hasMethods {
		// Pure data interface → struct.
		tr.out.line("type " + name + " struct {")
		tr.out.indent()
		for _, m := range members {
			if err := tr.emitInterfaceMember(m); err != nil {
				return err
			}
		}
		tr.out.dedent()
		tr.out.line("}")
		tr.out.blank()
		return nil
	}
	// Interface with methods → Go interface.
	tr.out.line("type " + name + " interface {")
	tr.out.indent()
	for _, m := range members {
		if ast.IsMethodSignatureDeclaration(m.ASTNode()) {
			params, ret, err := tr.signatureFromChildren(m)
			if err != nil {
				return err
			}
			tr.out.line(m.Name() + "(" + params + ")" + ret)
		}
	}
	tr.out.dedent()
	tr.out.line("}")
	tr.out.blank()
	return nil
}

func (tr *transpiler) emitInterfaceMember(m tsmorph.Node) error {
	name := exportField(m.Name())
	typ, err := tr.memberType(m)
	if err != nil {
		return err
	}
	tr.out.line(name + " " + typ)
	return nil
}

// memberType computes the Go field type for an interface/class member,
// mapping optional (`x?: T`) to a pointer with an approx gap.
func (tr *transpiler) memberType(m tsmorph.Node) (string, error) {
	tn, ok := m.GetType()
	var typ string
	var err error
	if ok {
		typ, err = tr.goType(tn)
	} else {
		t := m.Type()
		if t.IsUnknown() {
			return "", fmt.Errorf("member %s has no type", m.Name())
		}
		typ = tr.cleanCheckerType(t.Text())
	}
	if err != nil {
		return "", err
	}
	if typ == "" {
		typ = "any"
	}
	if m.HasQuestionToken() {
		tr.recordGap(SevApprox, "optional", m, "optional property %s mapped to pointer", m.Name())
		typ = "*" + typ
	}
	return typ, nil
}

