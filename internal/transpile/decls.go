// signatureFromChildren renders `params) ret` from a node's parameter
// children and call-signature return type. The declared return type node is
// preferred over the checker's text so aliases (Money, uint8) survive.
func (tr *transpiler) signatureFromChildren(n tsmorph.Node) (params, ret string, err error) {
	var ps []string
	// Checker call signature (for contextual/JS types of unannotated params
	// and the return type) — may be empty for non-function nodes.
	var sigCheck []string // checker-rendered param types, aligned by index
	if sigs := n.Type().CallSignatures(); len(sigs) > 0 {
		for _, p := range sigs[0].Parameters() {
			sigCheck = append(sigCheck, p.Type.Text())
		}
	}
	pi := 0
	for _, c := range n.Children() {
		if !ast.IsParameterDeclaration(c.ASTNode()) {
			continue
		}
		name := c.Name()
		tn, ok := c.GetType()
		var typ string
		if ok {
			t, err := tr.goType(tn)
			if err != nil {
				return "", "", err
			}
			typ = t
		} else if pi < len(sigCheck) {
			// No annotation: the checker may still know the type from the
			// contextual/call-site type — that's a tightenable site (and the
			// JSDoc case for JS input).
			typ = "any"
			if ct := sigCheck[pi]; ct != "" && notAnyLike(ct) {
				tr.tightenable("param", c, tr.cleanCheckerType(ct), "any")
			}
		} else {
			typ = "any"
		}
		pi++
		ps = append(ps, name+" "+typ)
	}
	ret = ""
	// Declared return type (syntax-first: keeps alias names).
	if rn, ok := tr.returnTypeNode(n); ok {
		t, err := tr.goType(rn)
		if err != nil {
			return "", "", err
		}
		if t != "" {
			ret = " " + t
			return strings.Join(ps, ", "), ret, nil
		}
	}
	sigs := n.Type().CallSignatures()
	if len(sigs) > 0 && !sigs[0].ReturnType().IsVoid() {
		ret = " " + tr.cleanCheckerType(sigs[0].ReturnType().Text())
	}
	return strings.Join(ps, ", "), ret, nil
}

// returnTypeNode finds the declared return-type child of a function-like
// node (the type node following the parameter list).
func (tr *transpiler) returnTypeNode(n tsmorph.Node) (tsmorph.Node, bool) {
	// ts-go-morph's typed wrappers expose ReturnTypeNode directly.
	switch {
	case ast.IsFunctionDeclaration(n.ASTNode()):
		if fd, ok := n.AsFunctionDeclaration(); ok {
			return fd.ReturnTypeNode()
		}
	case ast.IsMethodDeclaration(n.ASTNode()):
		if md, ok := n.AsMethodDeclaration(); ok {
			return md.ReturnTypeNode()
		}
	}
	// Generic fallback: any type node after the parameter list is the return
	// type.
	for _, c := range n.Children() {
		if ast.IsTypeNode(c.ASTNode()) {
			if isTypeNodeAfterParams(n, c) {
				return c, true
			}
		}
	}
	return tsmorph.Node{}, false
}

// isTypeNodeAfterParams reports whether the type node appears after the
// node's parameter list (i.e. it is the return type, not a param type).
func isTypeNodeAfterParams(n, tn tsmorph.Node) bool {
	lastParamEnd := -1
	for _, c := range n.Children() {
		if ast.IsParameterDeclaration(c.ASTNode()) {
			if c.End() > lastParamEnd {
				lastParamEnd = c.End()
			}
		}
	}
	return lastParamEnd >= 0 && tn.Pos() > lastParamEnd
}
