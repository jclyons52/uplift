// emitEnum emits a TS enum as a Go typed constant block. Numeric enums get
// explicit values matching TS semantics (initializers respected, implicit
// members continue from the previous + 1); string enums become a named
// string type with string constants.
func (tr *transpiler) emitEnum(n tsmorph.Node) error {
	name := n.Name()
	members := n.GetMembers()

	isString := false
	for _, m := range members {
		if init, ok := m.GetInitializer(); ok {
			if strings.HasPrefix(strings.TrimSpace(init.Text()), `"`) ||
				strings.HasPrefix(strings.TrimSpace(init.Text()), `'`) {
				isString = true
				break
			}
		}
	}

	if isString {
		tr.out.line("type " + name + " string")
		tr.out.blank()
		tr.out.line("const (")
		tr.out.indent()
		for _, m := range members {
			v := ""
			if init, ok := m.GetInitializer(); ok {
				v = normalizeQuote(strings.TrimSpace(init.Text()))
			} else {
				// TS requires initializers on string enums; if missing, fall
				// back to the member name so output still compiles.
				v = `"` + m.Name() + `"`
			}
			tr.out.line(name + exportField(m.Name()) + " " + name + " = " + v)
		}
		tr.out.dedent()
		tr.out.line(")")
		tr.out.blank()
		return nil
	}

	// Numeric enum: emit explicit values (TS folds initializers; implicit
	// members continue from previous + 1), so `Savings = 5, Credit` → 5, 6.
	tr.out.line("type " + name + " int")
	tr.out.blank()
	tr.out.line("const (")
	tr.out.indent()
	value := 0
	for _, m := range members {
		v := value
		if init, ok := m.GetInitializer(); ok {
			t := strings.TrimSpace(init.Text())
			if parsed, err := strconv.Atoi(t); err == nil {
				v = parsed
			} else {
				// Non-literal initializer: emit verbatim for the LLM.
				tr.recordGap(SevTodo, "enum", m, "enum member %s.%s has non-literal initializer", name, m.Name())
				tr.out.line(name + exportField(m.Name()) + " " + name + " = " + t + " // TODO(ts2go): verify value")
				value++
				continue
			}
		}
		tr.out.line(name + exportField(m.Name()) + " " + name + " = " + strconv.Itoa(v))
		value = v + 1
	}
	tr.out.dedent()
	tr.out.line(")")
	tr.out.blank()
	return nil
}

