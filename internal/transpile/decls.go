// emitFunction emits a top-level function declaration. `async` functions
// are wrapped in the jsrt shim: the body runs in a goroutine returning a
// promise, with await mapped to jsrtAwait inside.
func (tr *transpiler) emitFunction(n tsmorph.Node) error {
	return tr.emitFunctionAs(n, false)
}

// emitFunctionAs emits a function declaration: `func name(params) ret {...}`
// at top level, or a local closure `name := func(params) ret {...}` when
// closure is set. TS allows function declarations nested inside functions;
// Go does not, so those become closures.
func (tr *transpiler) emitFunctionAs(n tsmorph.Node, closure bool) error {
	return tr.emitFunctionWithName(n, n.Name(), closure)
}

// emitFunctionWithName is emitFunctionAs with an explicit Go name (used for
// CJS exports where the source function is anonymous).
func (tr *transpiler) emitFunctionWithName(n tsmorph.Node, goName string, closure bool) error {
	params, ret, err := tr.signatureFromChildren(n)
	if err != nil {
		return err
	}
	isAsync := n.HasModifier(ast.ModifierFlagsAsync)
	if isAsync {
		tr.usedShim = true
		ret = " *jsrtPromise"
	}
	tr.retStack = append(tr.retStack, strings.TrimSpace(ret))
	defer func() { tr.retStack = tr.retStack[:len(tr.retStack)-1] }()
	if isAsync {
		tr.recordGap(SevApprox, "async", n, "async function via jsrt shim (goroutine-per-call); swap for native concurrency later")
		tr.retStack[len(tr.retStack)-1] = "any"
	}
	head := "func " + goName
	if closure {
		head = goName + " := func"
	}
	tr.out.line(head + "(" + params + ")" + ret + " {")
	tr.out.indent()
	if isAsync {
		tr.out.line("return jsrtAsync(func() any {")
		tr.out.indent()
	}
	if body, ok := n.GetBody(); ok {
		if err := tr.emitBlock(body); err != nil {
			return err
		}
	} else {
		tr.out.line(`panic("not implemented")`)
	}
	if isAsync {
		tr.out.dedent()
		tr.out.line("})")
	}
	tr.out.dedent()
	tr.out.line("}")
	if !closure {
		tr.out.blank()
	}
	return nil
}

// emitVariableStatement emits `const x = ...` / `let x: T = ...`.
func (tr *transpiler) emitVariableStatement(n tsmorph.Node) error {
	vs, _ := n.AsVariableStatement()
	for _, d := range vs.Declarations() {
		name := d.Name()
		init, hasInit := d.Initializer()
		tn, hasType := d.TypeNode()
		var typ string
		if hasType {
			t, err := tr.goType(tn)
			if err != nil {
				return err
			}
			typ = t
		}
		if hasInit {
			// Object literals with a declared type → typed struct literal
			// (the checker types the literal as an anonymous __object).
			if ast.IsObjectLiteralExpression(init.ASTNode()) && typ != "" && typ != "any" {
				expr, err := tr.typedObjectLiteral(init, typ)
				if err != nil {
					return err
				}
				tr.out.line("var " + name + " " + typ + " = " + expr)
				continue
			}
			expr, err := tr.emitExpr(init)
			if err != nil {
				return err
			}
			switch {
			case typ != "" && typ != "any" && strings.HasPrefix(expr, "any(nil)"):
				// A placeholder can't initialize a typed var (`var p string
				// = any(nil)` is not assignable); emit the declaration with
				// the TODO as a trailing comment.
				tr.out.line("var " + name + " " + typ + " " + placeholderComment(expr))
			case typ != "" && typ != "any":
				tr.out.line("var " + name + " " + typ + " = " + expr)
			case !hasType && init.Type().IsNumber():
				// `let s = 0` infers number (→ float64); a bare `:=` would
				// pick Go's int and break arithmetic with other numbers.
				tr.out.line("var " + name + " float64 = " + expr)
			default:
				// `:=` is illegal at package scope; top-level consts without
				// an explicit type become `var x = e` instead.
				if len(tr.retStack) == 0 {
					tr.out.line("var " + name + " = " + expr)
				} else {
					tr.out.line(name + " := " + expr)
				}
			}
			tr.markUsedIfUnused(name, n)
		} else if typ != "" {
			tr.out.line("var " + name + " " + typ)
		} else {
			tr.out.line("var " + name + " any")
		}
	}
	return nil
}

